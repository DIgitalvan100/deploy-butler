def translate(lang: str, key: str, **params: object) -> str:
    table = STRINGS.get(lang) or STRINGS["ru"]
    template = table.get(key) or STRINGS["ru"].get(key) or key
    if not params:
        return template
    rendered = template
    for name, value in params.items():
        rendered = rendered.replace("{" + name + "}", str(value))
    return rendered
